/*******************************************************************************
 * File Name    : kpm_defines.h
 * Description  : Defines GPIO pin numbers used for interfacing the
 *                4x4 Matrix Keypad with the LPC2129 microcontroller.
 *
 * Details:
 * ROW0 to ROW3 represent the four row pins of the keypad.
 * COL0 to COL3 represent the four column pins of the keypad.
 *
 ******************************************************************************/

/* Defines GPIO pin numbers for keypad row connections. */
#define ROW0 16
#define ROW1 17
#define ROW2 18
#define ROW3 19

/* Defines GPIO pin numbers for keypad column connections. */
#define COL0 20
#define COL1 21
#define COL2 22
#define COL3 23
