/*******************************************************************************
 * File Name    : types.h
 * Description  : Defines user-defined data types for the embedded system.
 *
 * Details:
 * This header file provides shorthand aliases for standard C data types
 * to improve code readability and maintain consistency throughout the
 * embedded application.
 *
 ******************************************************************************/

// Defines an unsigned 32-bit integer data type.
typedef unsigned int u32;

// Defines an unsigned 8-bit integer data type.
typedef unsigned char u8;

// Defines a signed 32-bit integer data type.
typedef int s32;

// Defines a signed 8-bit character data type.
typedef char s8;

// Defines a 32-bit floating-point data type.
typedef float f32;

// Defines an unsigned 16-bit integer data type.
typedef unsigned short int u16;
